def bootstrap_weights(n_base: int, n_boot: int, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    return rng.multinomial(n_base, np.full(n_base, 1.0 / n_base), size=n_boot).astype(np.float64)


def cell_sums(values: np.ndarray, base_inv: np.ndarray, reg_idx: np.ndarray, n_base: int, n_reg: int) -> np.ndarray:
    arr = np.zeros((n_base, n_reg))
    np.add.at(arr, (base_inv, reg_idx), values)
    return arr


def git_free_source_snapshot(files: Sequence[Path], dest: Path) -> List[Dict]:
    """Copy files (no git involved) and return their checksums."""
    import shutil
    rows = []
    for f in files:
        f = Path(f)
        d = dest / f
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, d)
        rows.append({"file": str(f), "sha256": sha256(f), "size": f.stat().st_size})
    return rows



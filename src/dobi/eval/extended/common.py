def sha256(path, limit_bytes: Optional[int] = None) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def checkpoint_path(policy: str, seed: int, project: str = PROJECT) -> Path:
    return Path(project) / LEARNED[policy].format(seed) / "weights/best.pt"



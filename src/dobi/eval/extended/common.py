@dataclass
class SplitContext:
    split: str
    table: DetectionTable
    meta: Dict[str, np.ndarray]
    regimes: np.ndarray
    reg_names: List[str]
    raw: Dict[str, Dict[str, np.ndarray]]      # stored regime sweeps (descending thr)
    asc: Dict[str, Dict[str, np.ndarray]]      # deduplicated ascending sweeps
    targets: Optional[Dict[str, np.ndarray]] = None   # roc/froc/pr [R, G] in reg_names order + grids


def load_split_context(split: str, db: str = DB, with_targets: bool = False) -> SplitContext:
    table, meta = load_split_detections(db, split, CLASS_ID, IOU_THR)
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    subs = sorted(get_split_subsets(conn, split, CLASS_ID, IOU_THR), key=lambda s: s["subset_id"])
    reg_names = [s["name"] for s in subs]
    raw = {s["name"]: load_raw_sweep(conn, s["subset_id"], CLASS_ID, IOU_THR) for s in subs}
    conn.close()
    ctx = SplitContext(split, table, meta, meta["regime"], reg_names, raw, {r: dedupe_sweep(v) for r, v in raw.items()})
    if with_targets:
        ci, fpr_g, fppi_g, roc, froc = build_cluster_targets(db, CLASS_ID, IOU_THR, U_MAX, EVAL_N_POINTS, EVAL_N_POINTS, split=split)
        ci_pr, rec_g, pr = build_pr_targets(db, CLASS_ID, IOU_THR, EVAL_N_POINTS, split=split)
        idx = {c["name"]: c["index"] for c in ci}
        idx_pr = {c["name"]: c["index"] for c in ci_pr}
        ctx.targets = {"roc": np.stack([roc[idx[r]] for r in reg_names]), "froc": np.stack([froc[idx[r]] for r in reg_names]),
                       "pr": np.stack([pr[idx_pr[r]] for r in reg_names]),
                       "fpr_grid": fpr_g, "fppi_grid": fppi_g, "recall_grid": rec_g}
    return ctx


def train_gt_density(db: str = DB, split: str = "train") -> Dict[str, float]:
    """Mean number of GT persons per base image of a split (deployment-time constant; never computed on test)."""
    if split == "test":
        raise ValueError("object density must not be estimated from test ground truth")
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    n_img = conn.execute("SELECT COUNT(*) FROM images WHERE split = ?", (split,)).fetchone()[0]
    n_gt = conn.execute("SELECT COUNT(*) FROM gt_objects g JOIN images i ON i.id = g.image_id WHERE i.split = ? AND g.class_id = ?",
                        (split, CLASS_ID)).fetchone()[0]
    conn.close()
    return {"split": split, "n_images": int(n_img), "n_gt": int(n_gt), "rho": n_gt / max(n_img, 1)}



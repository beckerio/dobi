def check_out_dir(out: Path) -> Path:
    """Outputs may only go to a run directory below paper_artifacts_extended_eval/."""
    out = Path(out).resolve()
    root = Path(OUT_ROOT).resolve()
    if root not in out.parents:
        raise SystemExit(f"refusing to write outside {root}: {out}")
    return out


def new_file(path: Path, overwrite_own: bool = False) -> Path:
    """Refuse to overwrite an existing file unless explicitly allowed (only for this run's own figures)."""
    path = Path(path)
    if path.exists() and not overwrite_own:
        raise FileExistsError(f"refusing to overwrite {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def jsonable(x):
    if isinstance(x, dict):
        return {str(k): jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return jsonable(x.tolist())
    if isinstance(x, (np.floating, float)):
        x = float(x)
        return None if not np.isfinite(x) else x
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.bool_):
        return bool(x)
    return x


def write_json(obj, path: Path, overwrite_own=False):
    new_file(path, overwrite_own).write_text(json.dumps(jsonable(obj), indent=2, allow_nan=False))


def write_table(df, stem: Path, caption: str, fmt="{:.4f}", overwrite_own=False):
    """CSV + Markdown + LaTeX (booktabs) of a DataFrame."""
    import pandas as pd  # noqa: F401
    stem = Path(stem)
    df.to_csv(new_file(stem.with_suffix(".csv"), overwrite_own), index=False)

    def cell(v):
        if isinstance(v, (float, np.floating)):
            return "–" if not np.isfinite(v) else fmt.format(v)
        return str(v)

    cols = list(df.columns)
    with open(new_file(stem.with_suffix(".md"), overwrite_own), "w") as f:
        f.write(f"<!-- {caption} -->\n| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n")
        for _, r in df.iterrows():
            f.write("| " + " | ".join(cell(r[c]) for c in cols) + " |\n")
    esc = lambda s: str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")
    with open(new_file(stem.with_suffix(".tex"), overwrite_own), "w") as f:
        f.write(f"% {caption}\n% generated by dobi.eval.extended - do not edit\n")
        f.write("\\begin{tabular}{" + "l" + "r" * (len(cols) - 1) + "}\n\\toprule\n")
        f.write(" & ".join(esc(c) for c in cols) + " \\\\\n\\midrule\n")
        for _, r in df.iterrows():
            f.write(" & ".join(esc(cell(r[c])) for c in cols) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")



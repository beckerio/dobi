def predict_functions(ckpt: Path, cache: FeatureCache, variant_ids: Sequence[int], tau_grid: np.ndarray = TAU,
                      device=None, batch: int = 4096) -> Dict[str, np.ndarray]:
    """Per-image predicted threshold functions {tpr, fpr, fppi, precision}: float32 [N, Q]."""
    device = device or torch.device("cuda" if torch.cuda.is_available() else "cpu")
    ck = torch.load(ckpt, map_location="cpu", weights_only=False)
    ta = ck["train_args"]
    head = build_monitor_head(ta["head"], cache.feat_channels, ta)
    _load_monitor_head_from_ckpt(head, ck)
    head.to(device).eval()
    rows = np.asarray([cache.row_for_variant(int(v)) for v in variant_ids])
    tg = torch.as_tensor(tau_grid, dtype=torch.float32, device=device)
    out = {k: np.empty((len(rows), len(tau_grid)), np.float32) for k in FUNC_KEYS}
    with torch.no_grad():
        for s in range(0, len(rows), batch):
            x = torch.from_numpy(cache.get(rows[s:s + batch])).to(device)
            d = decode_monitor_output(ta["head"], head, head(pooled_to_pseudo_feats(x, cache.feat_channels)), tg, ta.get("u_max", 2.0))
            for k in FUNC_KEYS:
                out[k][s:s + batch] = d[f"{k}_tau"].float().cpu().numpy()
    return out


def mean_behavior_functions(db: str = DB, tau_grid: np.ndarray = TAU) -> Dict[str, np.ndarray]:
    mb = MeanBehaviorPredictor(db, CLASS_ID, IOU_THR, tau_grid, split="train")
    return {"tpr": mb.curves["tpr_tau"], "fpr": mb.curves["fpr_tau"], "fppi": mb.curves["fppi_tau"],
            "precision": mb.curves["precision_tau"]}


def f1_of(funcs: Dict[str, np.ndarray]) -> np.ndarray:
    return safe_f1(funcs["precision"], funcs["tpr"])


def argmax_f1_tau(tpr: np.ndarray, precision: np.ndarray, tau_grid: np.ndarray = TAU) -> np.ndarray:
    """F1-optimal threshold of each row (first maximum = lowest tau; same rule as torch.argmax in select_operating_threshold)."""
    return tau_grid[np.argmax(safe_f1(precision, tpr), axis=-1)]


def fppi_constrained_tau(tpr: np.ndarray, fppi: np.ndarray, budget: float, tau_grid: np.ndarray = TAU) -> np.ndarray:
    """
    Max predicted TPR subject to predicted FPPI <= budget (rows of [N, Q] arrays), identical to
    tau_spline.select_operating_threshold(criterion='fppi'): first maximum; if no threshold is predicted
    feasible, the threshold with the lowest predicted FPPI.
    """
    tpr, fppi = np.atleast_2d(tpr), np.atleast_2d(fppi)
    score = np.where(fppi <= budget, tpr, -np.inf)
    idx = np.argmax(score, axis=1)
    none = np.isinf(score).all(axis=1)
    idx[none] = np.argmin(fppi[none], axis=1)
    return tau_grid[idx]


# ------------------------------------------------------------------
# geometric curve errors (unchanged evaluation conversion)
# ------------------------------------------------------------------
_G: Dict = {}


def _geo_worker(args):
    tpr, fpr, fppi, prec, ridx = args
    t = _G["targets"]
    out = np.empty((len(tpr), 3))
    for i in range(len(tpr)):
        c = {"tpr_tau": tpr[i], "recall_tau": tpr[i], "fpr_tau": fpr[i], "fppi_tau": fppi[i], "precision_tau": prec[i]}
        roc, froc, pr = tau_curves_to_geometric(c, t["fpr_grid"], t["fppi_grid"], t["recall_grid"])
        r = ridx[i]
        out[i] = (np.mean(np.abs(roc - t["roc"][r])), np.mean(np.abs(froc - t["froc"][r])), np.mean(np.abs(pr - t["pr"][r])))
    return out


def geometric_mads(funcs: Dict[str, np.ndarray], regime_index: np.ndarray, targets: Dict[str, np.ndarray],
                   workers: int = 20, chunk: int = 256) -> np.ndarray:
    """MAD (ROC, FROC, PR) of each row of funcs against the regime target of that row: [N, 3]."""
    from multiprocessing import get_context
    _G["targets"] = targets
    n = len(regime_index)
    jobs = [(funcs["tpr"][s:s + chunk], funcs["fpr"][s:s + chunk], funcs["fppi"][s:s + chunk],
             funcs["precision"][s:s + chunk], regime_index[s:s + chunk]) for s in range(0, n, chunk)]
    if workers <= 1 or n < 2 * chunk:
        return np.concatenate([_geo_worker(j) for j in jobs]) if jobs else np.zeros((0, 3))
    with get_context("fork").Pool(workers) as pool:
        return np.concatenate(pool.map(_geo_worker, jobs))


# ------------------------------------------------------------------
# empirical per-image counts on the threshold grid (for labelled references)
# ------------------------------------------------------------------
def per_image_grid_counts(table: DetectionTable, tau_grid: np.ndarray = TAU):
    """TP[i, q], FP[i, q] = counts of image i's detections with score >= tau_grid[q] (int32 [N, Q])."""
    tg = tau_grid.astype(np.float64)
    owner = table.det_owner()
    # detection j is kept at grid index q iff tg[q] <= score_j  <=>  q < searchsorted(tg, score_j, 'right')
    k = np.searchsorted(tg, table.scores, side="right")
    Q = len(tg)
    tp = np.zeros((table.n, Q + 1), np.int32)
    fp = np.zeros((table.n, Q + 1), np.int32)
    np.add.at(tp, (owner[table.is_tp], k[table.is_tp]), 1)
    np.add.at(fp, (owner[~table.is_tp], k[~table.is_tp]), 1)
    # count at q = number of detections with k > q  -> reverse cumulative sum over k, shifted
    tp = np.cumsum(tp[:, ::-1], axis=1)[:, ::-1][:, 1:]
    fp = np.cumsum(fp[:, ::-1], axis=1)[:, ::-1][:, 1:]
    return tp, fp


def empirical_functions(tp: np.ndarray, fp: np.ndarray, n_gt: np.ndarray, n_img: np.ndarray) -> Dict[str, np.ndarray]:
    """Threshold functions of pooled counts (rows), with the definitions of generate_curves."""
    tp = tp.astype(np.float64)
    fp = fp.astype(np.float64)
    n_gt = np.asarray(n_gt, np.float64)[..., None]
    n_img = np.asarray(n_img, np.float64)[..., None]
    fp_total = np.maximum(fp[..., :1], 1.0)          # tau grid starts at 0 <= every stored score
    npred = tp + fp
    return {"tpr": tp / np.maximum(n_gt, 1.0), "fpr": fp / fp_total, "fppi": fp / np.maximum(n_img, 1.0),
            "precision": np.where(npred > 0, tp / np.maximum(npred, 1.0), 1.0)}



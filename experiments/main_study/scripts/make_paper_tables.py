"""
Generate all DOBI paper tables (LaTeX tabular + CSV + Markdown) from the final result files.

    PYTHONPATH=src python scripts/make_paper_tables.py \
        --paper_results paper_artifacts --execution_results paper_artifacts_execution --out paper_submission/tables

Main:        tab_curve_fit, tab_operational, tab_ablation
Supplement:  tabS_operational_full, tabS_per_regime_execution, tabS_heldout, tabS_area_errors
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

POL_NAME = {"fixed_pristine": "Fixed pristine", "mean_behavior": "Mean behavior", "adaptive_linear": "Linear",
            "adaptive_pchip": "Adaptive PCHIP", "pc1_behavior": "PC1 behavior", "pchip_regime_mean_tau": "PCHIP regime mean",
            "regime_id_validation": "Regime-ID", "regime_oracle": "Regime oracle"}
REGIME = {"pristine": "Pristine", "brightness_3_5": "Brightness", "contrast_3_5": "Contrast", "defocus_blur_3_5": "Defocus blur",
          "fog_3_5": "Fog", "frost_3_5": "Frost", "gaussian_blur_3_5": "Gaussian blur", "gaussian_noise_3_5": "Gaussian noise",
          "glass_blur_3_5": "Glass blur", "impulse_noise_3_5": "Impulse noise", "jpeg_compression_3_5": "JPEG",
          "motion_blur_3_5": "Motion blur", "pixelate_3_5": "Pixelate", "saturate_3_5": "Saturate", "shot_noise_3_5": "Shot noise",
          "snow_3_5": "Snow", "spatter_3_5": "Spatter", "speckle_noise_3_5": "Speckle noise"}


def emit(df: pd.DataFrame, latex_rows, header, stem: Path, colspec: str, note: str = ""):
    """df -> csv/md (full precision), latex_rows (pre-formatted strings) -> booktabs tabular."""
    df.to_csv(f"{stem}.csv", index=False)
    with open(f"{stem}.md", "w") as f:
        if note:
            f.write(f"<!-- {note} -->\n")
        f.write("| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n")
        for _, r in df.iterrows():
            f.write("| " + " | ".join(f"{v:.4f}" if isinstance(v, float) else str(v) for v in r) + " |\n")
    with open(f"{stem}.tex", "w") as f:
        f.write(f"% generated by scripts/make_paper_tables.py -- do not edit by hand. {note}\n")
        f.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n")
        for row in latex_rows:
            f.write(row if row.startswith("\\midrule") else row + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


def f4(v):
    return f"{v:.4f}"


def pm(m, s):
    return f"${m:.4f}\\!\\pm\\!{s:.4f}$"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper_results", default='results/main_study/paper_artifacts')
    ap.add_argument("--execution_results", default='results/main_study/paper_artifacts_execution')
    ap.add_argument("--out", default='outputs/tables')
    a = ap.parse_args()
    pa, pe, out = Path(a.paper_results), Path(a.execution_results), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    # ---------------- Table 1: curve fit ----------------
    cf = pd.read_csv(pa / "aggregate/curve_fit_summary.csv").set_index("model")
    rows, recs = [], []
    for m, name in (("mean_behavior", "Mean behavior"), ("adaptive_linear", "Linear"), ("adaptive_pchip", "Adaptive PCHIP")):
        e = cf.loc[m]
        vals = [(e[f"macro_mad_{k}_mean"], e[f"macro_mad_{k}_std"]) for k in ("roc", "froc", "pr")]
        recs.append({"model": name, "n_seeds": int(e["n_seeds"]), **{f"{k}_mad_mean": v[0] for k, v in zip(("roc", "froc", "pr"), vals)},
                     **{f"{k}_mad_std": v[1] for k, v in zip(("roc", "froc", "pr"), vals)}})
        best = {k: min(cf.loc[x, f"macro_mad_{k}_mean"] for x in ("adaptive_linear", "adaptive_pchip")) for k in ("roc", "froc", "pr")}
        cells = []
        for k, (mu, sd) in zip(("roc", "froc", "pr"), vals):
            txt = f4(mu) if m == "mean_behavior" else pm(mu, sd)
            if m != "mean_behavior" and abs(mu - best[k]) < 1e-12:
                txt = txt.replace(f"{mu:.4f}", f"\\mathbf{{{mu:.4f}}}") if txt.startswith("$") else f"\\textbf{{{txt}}}"
            cells.append(txt)
        rows.append(" & ".join([name] + cells))
    emit(pd.DataFrame(recs), rows, "Model & ROC MAD & FROC MAD & PR MAD", out / "tab_curve_fit", "lccc",
         "source: paper_artifacts/aggregate/curve_fit_summary.csv (macro over 18 test regimes; mean/sd over 3 seeds)")

    # ---------------- Table 2: operational (true per-image execution) ----------------
    ov = pd.read_csv(pe / "tables/per_image_execution_overall.csv").set_index("policy")
    order = ["fixed_pristine", "mean_behavior", "pc1_behavior", "adaptive_pchip", "regime_id_validation", "regime_oracle"]
    rows, recs = [], []
    for p in order:
        e = ov.loc[p]
        recs.append({"policy": POL_NAME[p], "deployable": bool(e["deployable"]), "macro_regime_f1": e["macro_regime_f1"],
                     "macro_regime_f1_seed_std": e["macro_regime_f1_seed_std"], "micro_f1": e["micro_f1"],
                     "execution_regret_macro": e["macro_execution_regret"], "micro_fppi": e["micro_fppi"]})
        if p == "regime_id_validation":
            rows.append("\\midrule\n")
        macro = pm(e["macro_regime_f1"], e["macro_regime_f1_seed_std"]) if e["macro_regime_f1_seed_std"] > 0 else f4(e["macro_regime_f1"])
        name = POL_NAME[p] + ("$^\\dagger$" if not e["deployable"] else "")
        rows.append(" & ".join([name, macro, f4(e["micro_f1"]), f4(e["macro_execution_regret"]), f"{e['micro_fppi']:.3f}"]))
    emit(pd.DataFrame(recs), rows, "Policy & Macro $F_1$ & Micro $F_1$ & Regret & FPPI", out / "tab_operational", "lcccc",
         "source: paper_artifacts_execution/tables/per_image_execution_overall.csv (true per-image execution, 85,800 test variants)")

    # ---------------- Table 3: ablations ----------------
    ab = pd.read_csv(pa / "aggregate/ablation_results.csv")
    rows = []
    for _, e in ab.iterrows():
        src = {"uniform": "uniform", "quantile (all scores)": "all-score q.", "quantile (TP scores)": "TP-score q."}[e["knot_source"]]
        name = ("Linear" if e["interpolation"] == "linear" else "PCHIP") + ", " + src + (" + soft $\\tau$" if e["aux_tau_loss"] else "")
        rows.append(" & ".join([name, str(int(e["num_knots"])), f4(e["roc_mad"]), f4(e["froc_mad"]), f4(e["pr_mad"]),
                                f"{e['gain_vs_pristine']:+.4f}", f4(e["oracle_regret"])]))
    emit(ab, rows, "Variant & $K$ & ROC & FROC & PR & Gain$^\\ddagger$ & Regret$^\\ddagger$", out / "tab_ablation", "lcccccc",
         "source: paper_artifacts/aggregate/ablation_results.csv (single seed 0; Gain/Regret = regime-curve utility)")

    # ---------------- Supplement: full operational table ----------------
    full = ["fixed_pristine", "mean_behavior", "adaptive_linear", "pc1_behavior", "adaptive_pchip",
            "pchip_regime_mean_tau", "regime_id_validation", "regime_oracle"]
    rows, recs = [], []
    for p in full:
        e = ov.loc[p]
        recs.append({"policy": POL_NAME[p], **{c: e[c] for c in ("micro_precision", "micro_recall", "micro_f1", "micro_fppi",
                                                                  "macro_regime_f1", "macro_execution_gain", "macro_execution_regret",
                                                                  "n_regimes_improved", "n_regimes_degraded")}})
        if p == "pchip_regime_mean_tau":
            rows.append("\\midrule\n")
        rows.append(" & ".join([POL_NAME[p] + ("$^\\dagger$" if not e["deployable"] else ""), f"{e['micro_precision']:.3f}",
                                f"{e['micro_recall']:.3f}", f4(e["micro_f1"]), f"{e['micro_fppi']:.3f}", f4(e["macro_regime_f1"]),
                                f"{e['macro_execution_gain']:+.4f}", f4(e["macro_execution_regret"]),
                                f"{int(e['n_regimes_improved'])}/{int(e['n_regimes_degraded'])}"]))
    emit(pd.DataFrame(recs), rows, "Policy & P & R & Micro $F_1$ & FPPI & Macro $F_1$ & Gain & Regret & +/$-$",
         out / "tabS_operational_full", "lcccccccc", "source: per_image_execution_overall.csv")

    # ---------------- Supplement: per-regime execution ----------------
    pr = pd.read_csv(pe / "tables/per_image_execution_per_regime.csv")
    w = pr.pivot(index="regime", columns="policy")
    regs = list(json.loads((pe / "execution_summary.json").read_text())["per_regime"]["adaptive_pchip"].keys())
    rows, recs = [], []
    for r in regs:
        rec = {"regime": REGIME[r], "tau_oracle": w.loc[r, ("tau_mean", "regime_oracle")],
               "tau_pchip_mean": w.loc[r, ("tau_mean", "adaptive_pchip")]}
        for p in ("fixed_pristine", "mean_behavior", "adaptive_pchip", "regime_id_validation", "regime_oracle"):
            rec[f"f1_{p}"] = w.loc[r, ("f1", p)]
        rec["gain_pchip"] = w.loc[r, ("execution_gain", "adaptive_pchip")]
        recs.append(rec)
        rows.append(" & ".join([REGIME[r], f"{rec['tau_oracle']:.3f}", f"{rec['tau_pchip_mean']:.3f}"]
                               + [f4(rec[f"f1_{p}"]) for p in ("fixed_pristine", "mean_behavior", "adaptive_pchip",
                                                                "regime_id_validation", "regime_oracle")]
                               + [f"{rec['gain_pchip']:+.4f}"]))
    emit(pd.DataFrame(recs), rows, "Regime & $\\tau^*$ & $\\bar{\\hat\\tau}$ & Fixed & Mean & PCHIP & Reg.-ID & Oracle & Gain",
         out / "tabS_per_regime_execution", "lcccccccc", "source: per_image_execution_per_regime.csv")

    # ---------------- Supplement: held-out ----------------
    gen = pd.read_csv(pa / "aggregate/generalization_results.csv")
    rows, recs = [], []
    for reg in ("gaussian_noise_3_5", "glass_blur_3_5", "fog_3_5"):
        g = gen[gen.held_out_regime == reg]
        for kind, lab in (("held_out_pchip", "held-out PCHIP"), ("held_out_mean_behavior", "held-out mean behavior"),
                          ("in_distribution_pchip", "in-distribution PCHIP (3 seeds)")):
            e = g[g.model == kind][["mad_roc", "mad_pr", "gain_vs_pristine", "oracle_regret", "tau_abs_error"]].mean()
            recs.append({"held_out": REGIME[reg], "model": lab, **e.to_dict()})
            rows.append(" & ".join([REGIME[reg] if kind == "held_out_pchip" else "", lab, f"{e['mad_roc']:.3f}", f"{e['mad_pr']:.3f}",
                                    f"{e['gain_vs_pristine']:+.3f}", f4(e["oracle_regret"]), f"{e['tau_abs_error']:.3f}"]))
    emit(pd.DataFrame(recs), rows, "Held-out type & Model & ROC MAD & PR MAD & Gain$^\\ddagger$ & Regret$^\\ddagger$ & $|\\Delta\\tau|$",
         out / "tabS_heldout", "llccccc", "source: paper_artifacts/aggregate/generalization_results.csv (single seed; regime-curve utility)")

    # ---------------- Supplement: area errors ----------------
    rows, recs = [], []
    for m, name in (("mean_behavior", "Mean behavior"), ("adaptive_linear", "Linear"), ("adaptive_pchip", "Adaptive PCHIP")):
        e = cf.loc[m]
        v = [e[f"macro_abs_delta_{k}_mean"] for k in ("auroc", "afroc", "auprc")]
        recs.append({"model": name, "abs_dAUROC": v[0], "abs_dAFROC": v[1], "abs_dAUPRC": v[2]})
        rows.append(" & ".join([name] + [f4(x) for x in v]))
    emit(pd.DataFrame(recs), rows, "Model & $|\\Delta$AUROC$|$ & $|\\Delta$AFROC$|$ & $|\\Delta$AUPRC$|$", out / "tabS_area_errors",
         "lccc", "source: curve_fit_summary.csv")
    # ---------------- Supplement: evaluation modes (macro) ----------------
    cmp_ = pd.read_csv(pe / "tables/evaluation_mode_comparison.csv")
    cm = cmp_[cmp_.regime.str.startswith("MACRO")]
    rows, recs = [], []
    for _, e in cm.iterrows():
        sub = cmp_[(cmp_.policy == e["policy"]) & ~cmp_.regime.str.startswith("MACRO")]
        same = int(((sub.old_gain > 1e-9) == (sub.new_gain > 1e-9)).sum())
        recs.append({"policy": POL_NAME[e["policy"]], "regime_curve_f1": e["old_f1"], "execution_f1": e["new_f1"],
                     "regime_curve_regret": e["old_regret"], "execution_regret": e["new_regret"], "same_gain_sign_regimes": same,
                     "max_abs_per_regime_f1_diff": float(sub.f1_difference_new_minus_old.abs().max())})
        rows.append(" & ".join([POL_NAME[e["policy"]], f4(e["old_f1"]), f4(e["new_f1"]), f4(e["old_regret"]), f4(e["new_regret"]),
                                f"{same}/18", f4(float(sub.f1_difference_new_minus_old.abs().max()))]))
    emit(pd.DataFrame(recs), rows, "Policy & \\multicolumn{2}{c}{Macro $F_1$} & \\multicolumn{2}{c}{Regret} & Same sign & max $|\\Delta F_1|$ \\\\\n"
         " & curve & exec. & curve & exec. & of gain & per regime", out / "tabS_modes", "lcccccc",
         "source: paper_artifacts_execution/tables/evaluation_mode_comparison.csv")

    # ---------------- Supplement: knot positions ----------------
    rows, recs = [], []
    for run, lab in (("tau_pchip_s0", "uniform"), ("abl_pchip_K16_quantile_all", "all-score quantiles"),
                     ("abl_pchip_K16_quantile_tp", "TP-score quantiles")):
        kn = json.loads((pa / "runs" / run / "resolved_config.json").read_text())["checkpoint_train_args"]["knots"]
        recs.append({"placement": lab, "knots": " ".join(f"{k:.4f}" for k in kn)})
        rows.append(lab + " & \\parbox[t]{0.78\\linewidth}{\\raggedright\\footnotesize " + ", ".join(f"{k:.4f}" for k in kn) + "}")
    emit(pd.DataFrame(recs), rows, "Placement & Knots $\\tau_1,\\ldots,\\tau_{16}$", out / "tabS_knots", "lp{0.8\\linewidth}",
         "source: paper_artifacts/runs/<run>/resolved_config.json (checkpoint train_args)")

    # ---------------- Supplement: PC1 baseline ----------------
    pc = json.loads((pa / "aggregate/pc1_baseline_summary.json").read_text())["per_seed"]["0"]
    ev = pc["explained_variance_ratio_first5"]
    rec = {"pc1_explained_variance": ev[0], "pc2": ev[1], "pc3": ev[2], "train_recon_rmse": pc["train_reconstruction_rmse_oracle_coefficient"],
           "test_recon_rmse": pc["test_reconstruction_rmse_oracle_coefficient"]}
    emit(pd.DataFrame([rec]), [" & ".join([f"{100 * ev[0]:.1f}\\%", f"{100 * ev[1]:.1f}\\%", f"{100 * ev[2]:.1f}\\%",
                                             f"{rec['train_recon_rmse']:.4f}", f"{rec['test_recon_rmse']:.4f}"])],
         "PC1 & PC2 & PC3 & Train RMSE & Test RMSE", out / "tabS_pc1", "ccccc",
         "source: paper_artifacts/aggregate/pc1_baseline_summary.json (vector [TPR,FPR,log1p FPPI,Prec]; RMSE with exact PC1 coefficient)")
    print("tables written to", out)


if __name__ == "__main__":
    main()

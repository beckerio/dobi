"""Generate LaTeX tables for the exploratory follow-up studies (E1, D1-D5, E2, E1-A2).

Source: results/rq4_followups (the folder that contains results/).
Usage:  python scripts/tables/make_followup_tables.py <bundle_dir> [<out_tables_dir>]
All numbers are read from the bundle; nothing is typed by hand.
"""
import csv, json, sys, os

B = os.path.join(sys.argv[1], "results")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join("outputs", "tables")
os.makedirs(OUT, exist_ok=True)
J = lambda f: json.load(open(os.path.join(B, f)))


def rows(f):
    with open(os.path.join(B, f), newline="") as fh:
        return {r["arm"]: r for r in csv.DictReader(fh)}


f3 = lambda x: f"{float(x):.4f}" if x not in ("", None) else "--"
f2 = lambda x: f"{float(x):.4f}"
pm = lambda m, s: f3(m) if float(s or 0) == 0 else f"{f3(m)}$\\pm${f3(s)}"


def ci(c):
    return f"{c['est']:+.4f} [{c['lo']:+.4f}, {c['hi']:+.4f}]"


e1b = rows("E1B_E1B_summary.csv")
e1c = rows("E1C_E1C_summary.csv")
e1a = rows("E1A_E1A_summary.csv")
e2m = J("E2_E2_main18_results.json")
e2a = J("E2_E2_e1a_results.json")
a2 = J("E1A2_results_with_pchip16_E1A2_results.json")
A2 = a2["summary"]

# ---------------------------------------------------------------- main table
m18 = {
    "mean": (e1b["mean_prior"]["mean_mad"], e1b["mean_prior"]["macro_f1"]),
    "p16": (e1b["main_pchip"]["mean_mad"], e1b["main_pchip"]["macro_f1"]),
    "p32": (e2m["arms"]["E2_pchip32"]["mean_mad"][0], e2m["arms"]["E2_pchip32"]["macro_f1"][0]),
    "tpl": (e2m["arms"]["E2_template"]["mean_mad"][0], e2m["arms"]["E2_template"]["macro_f1"][0]),
    "hard": (e1b["hard_lookup"]["mean_mad"], e1b["hard_lookup"]["macro_f1"]),
    "soft": (e2m["arms"]["soft_lookup_formula"]["mean_mad"][0], e2m["arms"]["soft_lookup_formula"]["macro_f1"][0]),
}
s4 = {
    "mean": e1a["A4_mean_prior"]["mean_mad"], "p16": e1a["A1_pchip35"]["mean_mad"],
    "p32": e2a["arms"]["E2_pchip32"]["mean_mad"][0], "tpl": e2a["arms"]["E2_template"]["mean_mad"][0],
    "hard": e1a["A2_hard_lookup"]["mean_mad"], "soft": e2a["arms"]["soft_lookup_formula"]["mean_mad"][0],
}
s24 = {
    "mean": A2["mean_prior"]["pooled_sev2_sev4"]["mean_mad"][0], "p16": A2["PCHIP16"]["pooled_sev2_sev4"]["mean_mad"][0],
    "p32": A2["K32"]["pooled_sev2_sev4"]["mean_mad"][0], "tpl": None,
    "hard": A2["hard_lookup"]["pooled_sev2_sev4"]["mean_mad"][0], "soft": A2["soft_lookup_formula"]["pooled_sev2_sev4"]["mean_mad"][0],
}
names = [("mean", "Mean behavior", "--"), ("p16", "PCHIP, 16 knots", "no"), ("p32", "PCHIP, 32 knots", "no"),
         ("tpl", "Template decoder", "no"), ("hard", "Hard lookup$^\\dagger$", "yes"), ("soft", "Soft lookup$^\\dagger$", "yes")]
L = ["\\begin{tabular}{lcccccc}", "\\toprule",
     " & Regime & \\multicolumn{2}{c}{18 regimes} & sev.\\,4 & sev.\\,2+4 \\\\",
     "\\cmidrule(lr){3-4}\\cmidrule(lr){5-5}\\cmidrule(lr){6-6}",
     "Arm & labels & MAD & $F_1$ & MAD & MAD \\\\", "\\midrule"]
for k, n, lab in names:
    L.append(f"{n} & {lab} & {f3(m18[k][0])} & {f3(m18[k][1])} & {f3(s4[k])} & {f3(s24[k])} \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_followup.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(L) + "\n")

# ------------------------------------------------- S: 18 regimes, all arms
L = ["\\begin{tabular}{lcccccc}", "\\toprule", "Arm & Mean MAD & ROC & FROC & PR & Macro $F_1$ & Micro $F_1$ \\\\", "\\midrule"]
def csvrow(name, r):
    return f"{name} & {pm(r['mean_mad'], r['mean_mad_sd']) if r['mean_mad'] else '--'} & {f3(r['macro_mad_roc'])} & {f3(r['macro_mad_froc'])} & {f3(r['macro_mad_pr'])} & {f3(r['macro_f1'])} & {f3(r['micro_f1'])} \\\\"
def jrow(name, a):
    return f"{name} & {pm(*a['mean_mad'])} & {f3(a['macro_mad_roc'][0])} & {f3(a['macro_mad_froc'][0])} & {f3(a['macro_mad_pr'][0])} & {f3(a['macro_f1'][0])} & {f3(a['micro_f1'][0])} \\\\"
L.append(csvrow("Mean behavior", e1b["mean_prior"]))
L.append(csvrow("Score-only PCHIP-16", e1c["score_only_pchip"]))
L.append(csvrow("PCHIP-16 (main paper)", e1b["main_pchip"]))
L.append(jrow("PCHIP-32", e2m["arms"]["E2_pchip32"]))
L.append(jrow("Template decoder", e2m["arms"]["E2_template"]))
L.append(csvrow("Hard lookup$^\\dagger$", e1b["hard_lookup"]))
L.append(jrow("Soft lookup$^\\dagger$", e2m["arms"]["soft_lookup_formula"]))
L.append(csvrow("Regime-ID$^\\ddagger$", e1b["regime_id"]))
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tabS_fu_regimes.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(L) + "\n")

# ------------------------------------------- S: interpolation (E1-A, E2, E1-A2)
L = ["\\begin{tabular}{lcccccc}", "\\toprule",
     " & \\multicolumn{2}{c}{Train $\\{3,5\\}$, test 4} & \\multicolumn{4}{c}{Train $\\{1,3,5\\}$, test $\\{2,4\\}$ (pre-specified)} \\\\",
     "\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}",
     "Arm & Mean MAD & Macro $F_1$ & Mean MAD & sev.\\,2 & sev.\\,4 & Macro $F_1$ \\\\", "\\midrule"]
def a2cols(k):
    if k is None:
        return "-- & -- & -- & --"
    s = A2[k]
    return f"{pm(*s['pooled_sev2_sev4']['mean_mad'])} & {f3(s['sev2_only']['mean_mad'][0])} & {f3(s['sev4_only']['mean_mad'][0])} & {f3(s['pooled_sev2_sev4']['macro_f1'][0])}"
spec = [
    ("Mean behavior", e1a["A4_mean_prior"], None, "mean_prior"),
    ("PCHIP-16", e1a["A1_pchip35"], None, "PCHIP16"),
    ("PCHIP-32", None, e2a["arms"]["E2_pchip32"], "K32"),
    ("Template decoder", None, e2a["arms"]["E2_template"], None),
    ("Hard lookup$^\\dagger$", e1a["A2_hard_lookup"], None, "hard_lookup"),
    ("Soft lookup$^\\dagger$", None, e2a["arms"]["soft_lookup_formula"], "soft_lookup_formula"),
]
for n, c, j, k in spec:
    left = f"{pm(c['mean_mad'], c['mean_mad_sd']) if c['mean_mad_sd'] not in ('', '0.0') else f3(c['mean_mad'])} & {f3(c['macro_f1'])}" if c else f"{pm(*j['mean_mad'])} & {f3(j['macro_f1'][0])}"
    L.append(f"{n} & {left} & {a2cols(k)} \\\\")
L.append("\\midrule")
L.append(f"Neighbor oracle$^\\ddagger$ & {f3(e1a['A6_neighbour_oracle']['mean_mad'])} & {f3(e1a['A6_neighbour_oracle']['macro_f1'])} & -- & -- & -- & -- \\\\")
L.append(f"PCHIP-16, sev.\\,4 seen$^\\ast$ & {pm(e1a['A5_ref_pchip52']['mean_mad'], e1a['A5_ref_pchip52']['mean_mad_sd'])} & {f3(e1a['A5_ref_pchip52']['macro_f1'])} & -- & -- & -- & -- \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tabS_fu_interp.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(L) + "\n")

# ---------------------------------------------------------- S: D1 decomposition
d1 = J("POSTHOC_D1_summary.json")["summary"]
L = ["\\begin{tabular}{llccccc}", "\\toprule",
     "Setup & Curve & PCHIP-16 floor & PCHIP-16 & Lookup floor & Hard lookup & Soft lookup \\\\", "\\midrule"]
for key, lab in [("18_regimes", "18 regimes"), ("sev4_17_E1A", "sev.\\,4")]:
    for c, cl in [("mad_roc", "ROC"), ("mad_froc", "FROC"), ("mad_pr", "PR"), ("mean", "Mean")]:
        r = d1[key][c]
        L.append(f"{lab if c=='mad_roc' else ''} & {cl} & {f3(r['pchip_floor'])} & {f3(r['pchip_result'])} & {f3(r['lookup_floor_correct_regime'])} & {f3(r['hard_lookup_result'])} & {f3(r['soft_lookup_result'])} \\\\")
    L.append("\\midrule" if key == "18_regimes" else "")
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tabS_fu_decomp.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(x for x in L if x) + "\n")

# ---------------------------------------------------------------- S: D5 knots
d5 = J("D5K3_D5_summary.json")["summary"]["train_18_regimes"]
L = ["\\begin{tabular}{lccccc}", "\\toprule", "Representation & Knots & ROC & FROC & PR & Mean \\\\", "\\midrule"]
for k, n in [("uniform_K16", "uniform (main paper)"), ("uniform_K24", "uniform"), ("uniform_K32", "uniform (selected)"),
             ("quantile_K16", "all-score quantiles"), ("logspaced_K16", "log-spaced")]:
    r = d5[k]
    L.append(f"{n} & {r['n_knots']} & {f3(r['mad_roc'])} & {f3(r['mad_froc'])} & {f3(r['mad_pr'])} & {f3(r['mean'])} \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tabS_fu_knots.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(L) + "\n")

# ----------------------------------------------------------- S: contrasts
C = a2["contrasts"]
L = ["\\begin{tabular}{llll}", "\\toprule", "Contrast & Conditions & $\\Delta$ mean MAD [95\\% CI] & $\\Delta$ macro $F_1$ [95\\% CI] \\\\", "\\midrule"]
for key, lab in [("K32 - soft_lookup_formula", "PCHIP-32 $-$ soft lookup"), ("K32 - hard_lookup", "PCHIP-32 $-$ hard lookup"),
                 ("K32 - PCHIP16", "PCHIP-32 $-$ PCHIP-16")]:
    if key not in C:
        continue
    for cs, cl in [("pooled_sev2_sev4", "sev.\\,2+4" + (" (primary)" if key.endswith("formula") else "")), ("sev2_only", "sev.\\,2"), ("sev4_only", "sev.\\,4")]:
        if cs in C[key]:
            L.append(f"{lab if cs=='pooled_sev2_sev4' else ''} & {cl} & {ci(C[key][cs]['mean_mad'])} & {ci(C[key][cs]['macro_f1'])} \\\\")
for setup, J2 in [("18 regimes", e2m), ("sev.\\,4, train $\\{3,5\\}$", e2a)]:
    for key, lab in [("E2_template - soft_lookup_formula", "Template $-$ soft lookup"), ("E2_pchip32 - soft_lookup_formula", "PCHIP-32 $-$ soft lookup")]:
        c = J2["contrasts"][key]
        L.append(f"{lab} & {setup} & {ci(c['mean_mad'])} & {ci(c['macro_f1'])} \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tabS_fu_contrasts.tex"), "w").write("% generated by scripts/make_followup_tables.py\n" + "\n".join(L) + "\n")
print("ok", sorted(C.keys()))

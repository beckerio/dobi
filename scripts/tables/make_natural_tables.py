# ------------------------------------------------ S: nearest-template matrices (row %)
def nearest(path, key_order):
    m = json.load(open(os.path.join(P, path)))["nearest_matrix"]
    regs, C = m["regimes"], m["counts"]
    short = [r.replace("S_", "").replace("residential", "resid.").replace("_", " ") for r in regs]
    L = ["\\begin{tabular}{l" + "c" * len(regs) + "}", "\\toprule",
         "True $\\backslash$ nearest & " + " & ".join(short) + " \\\\", "\\midrule"]
    for i, row in enumerate(C):
        tot = sum(row)
        cells = [(f"\\textbf{{{100*c/tot:.0f}}}" if i == j else f"{100*c/tot:.0f}") for j, c in enumerate(row)]
        L.append(f"{short[i]} ({tot:,}) & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return L
write("tabS_nat_nearest_vehicle.tex", nearest("N2/results/phase2_extra.json", None))
write("tabS_nat_nearest_person.tex", nearest("N3/results/n3_extra.json", None))


"""Generate LaTeX tables for the natural-condition studies (BDD100K: N2 vehicle, N3 person).

Source: results/natural_bdd (aggregate result files of the BDD100K studies).
Usage:  python scripts/tables/make_natural_tables.py <package_dir> [<out_tables_dir>]
All numbers are read from the package; nothing is typed by hand.
"""
import csv, os, sys
P = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join("outputs", "tables")
os.makedirs(OUT, exist_ok=True)
def rows(path):
    with open(os.path.join(P, path), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))
f4 = lambda x: f"{float(x):.4f}"
f3 = lambda x: f"{float(x):.3f}"
sg = lambda x: f"${float(x):+.4f}$"
ci = lambda d, lo, hi: f"{sg(d)} [{sg(lo)}, {sg(hi)}]"
num = lambda x: f"{int(float(x)):,}"
def write(name, lines):
    open(os.path.join(OUT, name), "w").write("% generated by scripts/make_natural_tables.py\n" + "\n".join(lines) + "\n")

n2a = {r["arm"]: r for r in rows("N2/results/phase2_arms.csv") if r["variant"] == "V-narrow"}
n3a = {r["arm"]: r for r in rows("N3/results/n3_arms.csv") if r["variant"] == "person"}
n2d = [r for r in rows("N2/results/phase2_deltas.csv") if r["variant"] == "V-narrow"]
n3d = [r for r in rows("N3/results/n3_deltas.csv") if r["variant"] == "person"]
def dl(D, label, comp, agg):
    for r in D:
        if r["label"] == label and r["comparison"] == comp and r["aggregation"] == agg:
            return r
    raise KeyError((label, comp, agg))

ARMS = [("prior", "Mean behavior"), ("bright16", "Brightness"), ("dobi16", "DOBI (PCHIP-16)"),
        ("soft", "Soft lookup$^\\dagger$"), ("oracle", "Regime oracle$^\\ddagger$")]

# ------------------------------------------------------------ main table (transposed: rows = studies)
L = ["\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{lccccc}", "\\toprule",
     "Objects & Prior & Brightness & DOBI & Soft lookup$^\\dagger$ & Oracle$^\\ddagger$ \\\\", "\\midrule"]
for study, A in [("Vehicles", n2a), ("Persons", n3a)]:
    L.append(study + " & " + " & ".join(f4(A[k]["M_macro"]) for k, _ in ARMS) + " \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
write("tab_natural.tex", L)

# --------------------------------------------- S: arms, both aggregations
L = ["\\begin{tabular}{llccccc}", "\\toprule",
     "Study & Arm & $M$ regime mean [95\\% CI] & seed SD & $M$ natural & $M$ day & $M$ night \\\\", "\\midrule"]
for study, A in [("Vehicles", n2a), ("Persons", n3a)]:
    for i, (k, n) in enumerate(ARMS + [("dobi32", "DOBI (PCHIP-32)")]):
        r = A[k]
        L.append(f"{study if i == 0 else ''} & {n} & {f4(r['M_macro'])} [{f4(r['M_macro_lo'])}, {f4(r['M_macro_hi'])}] & {f4(r['M_macro_seed_sd'])} & {f4(r['M_natural'])} & {f4(r['M_day'])} & {f4(r['M_night'])} \\\\")
    if study.startswith("Vehicles"):
        L.append("\\midrule")
L += ["\\bottomrule", "\\end{tabular}"]
write("tabS_nat_arms.tex", L)

# --------------------------------------------------------- S: contrasts
spec = [("H1", "dobi16 - prior", "macro", "H1: DOBI $-$ mean (binding)"),
        ("H2", "dobi16 - bright16", "macro", "H2: DOBI $-$ brightness (binding)"),
        ("natural", "dobi16 - prior", "natural", "DOBI $-$ mean, natural distribution"),
        ("natural", "dobi16 - bright16", "natural", "DOBI $-$ brightness, natural distribution"),
        ("H3_day", "dobi16 - bright16", "day", "DOBI $-$ brightness, day"),
        ("H3_night", "dobi16 - bright16", "night", "DOBI $-$ brightness, night"),
        ("H3_night", "dobi16 - prior", "night", "DOBI $-$ mean, night"),
        ("sec", "dobi16 - soft", "macro", "DOBI $-$ soft lookup"),
        ("exec", "dobi16 - fixed_tau (exec F1)", "macro", "Executed $F_1$: DOBI $-$ fixed $\\tau$"),
        ("exec", "soft - fixed_tau (exec F1)", "macro", "Executed $F_1$: soft lookup $-$ fixed $\\tau$")]
L = ["\\begin{tabular}{lcc}", "\\toprule", "Contrast & Vehicles & Persons \\\\", "\\midrule"]
for lab, comp, agg, name in spec:
    a, b = dl(n2d, lab, comp, agg), dl(n3d, lab, comp, agg)
    L.append(f"{name} & {ci(a['delta'], a['lo'], a['hi'])} & {ci(b['delta'], b['lo'], b['hi'])} \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
write("tabS_nat_contrasts.tex", L)

# ------------------------------------------------------ S: per regime
REG = ["S_city_day", "S_city_night", "S_highway_day", "S_highway_night", "S_residential_day", "S_residential_night"]
RN = ["city day", "city night", "highway day", "highway night", "resid.\\ day", "resid.\\ night"]
n2r = {r["arm"]: r for r in rows("N2/results/phase2_per_regime.csv") if r["variant"] == "V-narrow"}
n3r = {r["arm"]: r for r in rows("N3/results/n3_per_regime.csv") if r["variant"] == "person"}
QUAL3 = {"S_city_day", "S_city_night", "S_residential_day"}
L = ["\\begin{tabular}{ll" + "c" * 6 + "}", "\\toprule",
     "Study & Arm & " + " & ".join(n if (r in QUAL3) else n for r, n in zip(REG, RN)) + " \\\\", "\\midrule"]
for study, R in [("Vehicles", n2r), ("Persons", n3r)]:
    for i, (k, n) in enumerate(ARMS):
        vals = []
        for r in REG:
            v = f"{float(R[k][r]):.3f}"
            vals.append(v + ("$^\\ast$" if study.startswith("Persons") and r not in QUAL3 else ""))
        L.append(f"{study if i == 0 else ''} & {n} & " + " & ".join(vals) + " \\\\")
    if study.startswith("Vehicles"):
        L.append("\\midrule")
L += ["\\bottomrule", "\\end{tabular}"]
write("tabS_nat_regimes.tex", L)

# ------------------------------------------------- S: data tables T1-T5
def simple(path, cols, heads, align, name, fmt=None):
    R = rows(path)
    L = ["\\begin{tabular}{" + align + "}", "\\toprule", " & ".join(heads) + " \\\\", "\\midrule"]
    for r in R:
        cells = []
        for c in cols:
            v = r[c]
            cells.append((fmt or {}).get(c, lambda x: x.replace("N2 phase 2", "vehicle study").replace("(N3)", "(person study)").replace("N3 test regimes", "Person-study test regimes").replace("S_highway_day, S_highway_night, S_residential_night", "highway day, highway night, residential night").replace("_", "\\_").replace("%", "\\%").replace(">=", "$\\geq$").replace("<", "$<$"))(v))
        L.append(" & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write(name, L)
simple("data_documentation/tables/T1_weather_timeofday.csv", ["weather", "timeofday", "train", "val"], ["Weather", "Time of day", "Train", "Val"], "llrr", "tabS_bdd_t1.tex", {"train": num, "val": num})
simple("data_documentation/tables/T2_scene_timeofday.csv", ["scene", "timeofday", "train", "val"], ["Scene", "Time of day", "Train", "Val"], "llrr", "tabS_bdd_t2.tex", {"train": num, "val": num})
pr = lambda x: f"{100*float(x):.0f}"
reg = lambda x: x.replace("S_", "").replace("_", " ")
simple("data_documentation/tables/T3_regimes_parts.csv",
       ["regime", "part", "images", "prefixes", "persons", "riders", "vehicles", "pers <32", "pers 32-64", "pers ≥64", "veh <32", "veh 32-64", "veh ≥64"],
       ["Regime", "Part", "Images", "Prefixes", "Persons", "Riders", "Vehicles", "P$<$32", "P 32--64", "P$\\geq$64", "V$<$32", "V 32--64", "V$\\geq$64"],
       "llrrrrrrrrrrr", "tabS_bdd_t3.tex",
       {"regime": reg, "part": lambda x: x.replace("test (official val)", "test"), "images": num, "prefixes": num, "persons": num, "riders": num, "vehicles": num,
        "pers <32": pr, "pers 32-64": pr, "pers ≥64": pr, "veh <32": pr, "veh 32-64": pr, "veh ≥64": pr})
simple("data_documentation/tables/T4_class_mapping.csv", ["side", "class (label version name)", "group", "use"], ["Side", "Class (label name)", "Group", "Use"], "llll", "tabS_bdd_t4.tex")
simple("data_documentation/tables/T5_exclusions_leakage.csv", ["item", "count", "handling / result"], ["Item", "Count", "Handling / result"], "p{0.5\\textwidth}rp{0.3\\textwidth}", "tabS_bdd_t5.tex", {"count": num})

# ------------------------------------------------ S: N2 phase 1 weather regimes (vehicle, V-narrow)
import json
sep = [r for r in rows("N2/results/separation_distances.csv") if r["variant"] == "V-narrow" and r["pair"] == ""]
gain = [r for r in rows("N2/results/threshold_gains.csv") if r["variant"] == "V-narrow"]
WREG = [("R1_overcast_day", "overcast, day"), ("R2_rainy_day", "rainy, day"), ("R4_snowy_day", "snowy, day"),
        ("R8_dawn_dusk", "dawn/dusk"), ("R7_clear_night", "clear, night"), ("R3_rainy_night", "rainy, night"),
        ("R5_snowy_night", "snowy, night"), ("R6_foggy", "foggy$^\\ast$")]
VIEWS = [("all", "pooled"), ("lt32", "$<$32"), ("32to64", "32--64"), ("ge64", "$\\geq$64")]
def g1(reg, view, key):
    for r in sep:
        if r["regime"] == reg and r["view"] == view:
            return r[key]
def g2(reg, view):
    for r in gain:
        if r["regime"] == reg and r["view"] == view:
            return r
L = ["\\begin{tabular}{l" + "c" * 4 + "cc}", "\\toprule",
     " & \\multicolumn{4}{c}{Distance to clear day (by box height)} & \\multicolumn{2}{c}{Threshold gain $\\Delta F_1$} \\\\",
     "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}",
     "Regime & " + " & ".join(v for _, v in VIEWS) + " & pooled & $\\geq$64 \\\\", "\\midrule"]
for reg, name in WREG:
    d = [f"{float(g1(reg, v, 'std_l2_train')):.2f}" for v, _ in VIEWS]
    a, b = g2(reg, "all"), g2(reg, "ge64")
    L.append(f"{name} & " + " & ".join(d) + f" & {sg(a['gain'])} & {sg(b['gain'])} \\\\")
L.append("\\midrule")
L.append("Noise threshold & " + " & ".join(f"{float(g1('R1_overcast_day', v, 'noise_max')):.2f}" for v, _ in VIEWS) + " & -- & -- \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
write("tabS_nat_weather.tex", L)


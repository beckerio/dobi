"""Tables and figure for the continuous and compositional probing experiments.

Source: results/rq5_continuous (the folder that contains results/).
Usage:  python scripts/tables/make_continuous_tables.py <package_dir> [<out_tables_dir> [<out_figures_dir>]]
All numbers are read from the package CSV files; nothing is typed by hand.
"""
import csv
import os
import sys

P = os.path.join(sys.argv[1], "results")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join("outputs", "tables")
FIG = sys.argv[3] if len(sys.argv) > 3 else os.path.join("outputs", "figures", "main")
os.makedirs(OUT, exist_ok=True)
os.makedirs(FIG, exist_ok=True)


def rows(f):
    with open(os.path.join(P, f), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def num(x):
    return float(x)


def sg(x, d=4):
    return f"${num(x):+.{d}f}$"


def f4(x):
    return f"{num(x):.4f}"


def pct(x):
    return f"{100 * num(x):.0f}\\%"


def write(name, lines):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by scripts/make_continuous_tables.py\n" + "\n".join(lines) + "\n")



# ------------------------------------------------------------- S: monitors (M) per set, both experiments
def arms_table(f, sets, name, with_oracle):
    A = [r for r in rows(f) if r["metric"] == "M"]
    get = {(r["arm"], r["set"]): r for r in A}
    L = ["\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{l" + "c" * len(sets) + "}", "\\toprule",
         "Monitor & " + " & ".join(s[1] for s in sets) + " \\\\", "\\midrule"]
    for a in ARM_ORDER:
        if a == "oracle_replicate_not_deployable" and not with_oracle:
            continue
        cells = []
        for s, _ in sets:
            r = get.get((a, s))
            if r is None:
                cells.append("--")
            else:
                sd = r.get("seed_sd", "")
                cells.append(f4(r["est"]) + (f"$\\pm${f4(sd)}" if sd not in ("", "NA", "0", "0.0") and num(sd) > 0 else ""))
        L.append(f"{ARM[a]} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write(name, L)


